export function getAllCards(): Card[] {
  return CARDS_DATA;
}

export function getManilhas(): Card[] {
  return CARDS_DATA
    .filter((c) => c.isManilha)
    .sort((a, b) => (a.manilhaRank || 99) - (b.manilhaRank || 99));
}

export function getFeaturedCard(): Card {
  // Returns O Zap (4 de Paus) as the supreme feature card
  const zap = CARDS_DATA.find((c) => c.id === 'paus-4-zap');
  return zap || CARDS_DATA[0];
}

export function getCardById(id: string): Card | undefined {
  return CARDS_DATA.find((c) => c.id === id);
}

export function filterCards(
  cards: Card[],
  searchQuery: string,
  suitFilter: string,
  categoryFilter: string
): Card[] {
  return cards.filter((card) => {
    // Search query matching name, value, tags
    if (searchQuery.trim()) {
      const q = searchQuery.toLowerCase().trim();
      const matchName = card.name.toLowerCase().includes(q);
      const matchValue = card.value.toLowerCase().includes(q);
      const matchSuit = card.suit.toLowerCase().includes(q);
      const matchTags = card.tags.some((t) => t.toLowerCase().includes(q));
      if (!matchName && !matchValue && !matchSuit && !matchTags) {
        return false;
      }
    }

    // Suit filter
    if (suitFilter !== 'ALL' && card.suit !== suitFilter) {
      return false;
    }

    // Category filter
    if (categoryFilter !== 'ALL') {
      if (categoryFilter === 'MANILHA' && !card.isManilha) return false;
      if (categoryFilter === 'FIGURA' && card.category !== 'FIGURA') return false;
      if (categoryFilter === 'NUMERICA' && (card.category !== 'NUMERICA' || card.isManilha)) return false;
      if (categoryFilter === 'ARCANO' && card.category !== 'ARCANO') return false;
    }

    return true;
  });
}
